/* ------------------------------ helpers -------------------------------- */
const BY_ID = Object.fromEntries(ROUTES.map((r) => [r.id, r]));

export function getRoute(id) {
  return BY_ID[id] || null;
}

/** The concrete URL a route's primary CTA should point to. */
export function routeTargetHref(route) {
  if (!route) return { url: "/route-finder/", external: false };
  if (route.page) return { url: route.page, external: false };
  if (route.ecosystemKey) {
    const link = resolveLink(route.ecosystemKey);
    if (link) return { url: link.url, external: true };
  }
  return { url: "/route-finder/", external: false };
}

/** Resolve a route's `next` node into { href, label, external }. */
export function resolveNext(route) {
  const n = route && route.next;
  if (!n) return null;
  if (n.id) {
    const target = getRoute(n.id);
    const t = routeTargetHref(target);
    return { href: t.url, label: n.label, external: t.external };
  }
  if (n.key) {
    const link = resolveLink(n.key);
    if (link) return { href: link.url, label: n.label, external: link.external };
    return { href: "/route-finder/", label: n.label, external: false };
  }
  return { href: n.href || "/route-finder/", label: n.label, external: false };
}

export function routesByStage(stage) {
  return ROUTES.filter((r) => r.lifecycleStage === stage);
}

/** Serializable copy for /public/data/routes.json (no functions/links). */
